"""Build js/words.js from word frequencies in local documentation.

Usage: python3 -I scripts/build_words.py <docs-dir> <out-file>

Counts words in all .rst/.md/.txt files below <docs-dir>, keeps words that
exist in /usr/share/dict/words, and writes the most frequent ones.
"""
import collections
import json
import os
import re
import sys

MAX_WORDS = 2000
WORD = re.compile(r"(?<![\w/.-])([a-z]{2,12})(?![\w/-])")

docs, out = sys.argv[1], sys.argv[2]

with open("/usr/share/dict/words") as f:
    dictionary = {w.strip() for w in f if w.strip().islower()}
dictionary |= {"a", "i"}

counts = collections.Counter()
for root, _, files in os.walk(docs):
    if "/.git" in root or "node_modules" in root:
        continue
    for name in files:
        if not name.endswith((".rst", ".md", ".txt")):
            continue
        try:
            with open(os.path.join(root, name), errors="ignore") as f:
                text = f.read()
        except OSError:
            continue
        # Skip code blocks and inline code, they are mostly identifiers.
        text = re.sub(r"```.*?```|`[^`\n]*`|::\n(?:\n|[ \t]+.*\n)+", " ", text, flags=re.S)
        for w in WORD.findall(text):
            if w in dictionary:
                counts[w] += 1

words = [w for w, _ in counts.most_common(MAX_WORDS)]
with open(out, "w") as f:
    f.write("// Generated by scripts/build_words.py from local docs, ordered by frequency.\n")
    f.write("window.WORDS = " + json.dumps(words) + ";\n")
print(f"{len(words)} words written to {out}")
